import argparse
import re
import sys
from pathlib import Path
from PIL import Image

# Local index 0 is always transparent. Opaque colours get local indices 1..N,
# in order of first appearance (top-left to bottom-right).
# The engine merges every sprite's colours into the room palette at room load,
# so this script never needs to know about the engine's palette.

TRANSPARENT_INDEX = 0
ALPHA_THRESHOLD = 128   # alpha below this = transparent
MAX_COLOURS = 255       # local indices 1..255 (uint8_t)


def quantise_5bit(rgb):
    """The GBA stores 5 bits per channel, so colours that only differ in the
    low 3 bits are the same colour on hardware. Treat them as one."""
    return (rgb[0] >> 3, rgb[1] >> 3, rgb[2] >> 3)


def convert(input_path, output_path, name, max_colours):
    image = Image.open(input_path).convert("RGBA")
    width, height = image.size

    if width > 255 or height > 255:
        sys.exit(f"Error: sprite is {width}x{height}; width/height must each be <= 255.")

    # Optionally reduce the number of colours first (keeps alpha as-is).
    if max_colours < MAX_COLOURS:
        alpha = image.getchannel("A")
        reduced = image.convert("RGB").quantize(colors=max_colours, dither=Image.Dither.NONE)
        image = reduced.convert("RGB").convert("RGBA")
        image.putalpha(alpha)

    # key (5-bit RGB) -> local index
    index_of = {}
    # local index -> first-seen 8-bit colour, for readable output
    colours = []
    pixels = []

    raw = image.tobytes()  # RGBA, 4 bytes per pixel

    for i in range(0, len(raw), 4):
        r, g, b, a = raw[i], raw[i + 1], raw[i + 2], raw[i + 3]
        if a < ALPHA_THRESHOLD:
            pixels.append(TRANSPARENT_INDEX)
            continue

        key = quantise_5bit((r, g, b))

        if key not in index_of:
            if len(colours) >= MAX_COLOURS:
                sys.exit(
                    f"Error: {input_path} uses more than {MAX_COLOURS} distinct colours. "
                    f"Re-run with --max-colours N to reduce them."
                )
            colours.append((r, g, b))
            index_of[key] = len(colours)  # local indices start at 1

        pixels.append(index_of[key])

    upper = name.upper()

    # Pixel rows.
    rows = []
    for y in range(height):
        row = pixels[y * width:(y + 1) * width]
        rows.append("        " + ", ".join(map(str, row)) + ",")

    # Colour table. colors[0] is unused.
    colour_lines = ["        0,"]
    for i, (r, g, b) in enumerate(colours, start=1):
        colour_lines.append(f"        RGB8({r}, {g}, {b}),  // {i}")

    nl = "\n"
    output = f"""\
// Generated by png2sprite.py from {Path(input_path).name} ({width}x{height}, {len(colours)} colours)

// ---- Paste inside `namespace SpriteData {{ ... }}` in sprites.h ----

    inline constexpr uint16_t {upper}_COLORS[] = {{
{nl.join(colour_lines)}
    }};

    inline constexpr uint8_t {upper}[] = {{
{nl.join(rows)}
    }};

// ---- Then add these to sprites.h ----
//
// 1. In enum SpriteId (before SPRITE_COUNT):
//        SPR_{upper},
//
// 2. In struct DSprite:
//        static const DSprite {upper};
//
// 3. With the other definitions at the bottom:
//        inline const DSprite DSprite::{upper} = {{
//            SPR_{upper}, {width}, {height}, SpriteData::{upper}, SpriteData::{upper}_COLORS, {len(colours)}
//        }};
//
// 4. Map a tile ID to it in getSprite() (main.cpp) if it's a tile.
"""

    Path(output_path).write_text(output)

    print(f"Converted {input_path}")
    print(f"Dimensions: {width}x{height}")
    print(f"Colours: {len(colours)}")
    print(f"Output: {output_path}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description="Convert a PNG into a C++ sprite with its own colour table."
    )

    parser.add_argument("input", help="Input PNG")
    parser.add_argument("-o", "--output", default=None)
    parser.add_argument("-n", "--name", default=None)
    parser.add_argument(
        "-m", "--max-colours", type=int, default=MAX_COLOURS,
        help="Reduce the image to at most this many colours first (default: no reduction)"
    )

    args = parser.parse_args()

    name = args.name or Path(args.input).stem
    name = re.sub(r"\W+", "_", name)

    output = args.output or f"{name}.h"

    if not 1 <= args.max_colours <= MAX_COLOURS:
        sys.exit(f"--max-colours must be between 1 and {MAX_COLOURS}")

    convert(args.input, output, name, args.max_colours)